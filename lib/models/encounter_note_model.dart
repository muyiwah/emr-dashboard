        if (distressLevel != null) 'distress_level': distressLevel,
      };

  factory PatientCondition.fromJson(Map<String, dynamic> json) {
    return PatientCondition(
      overallCondition: json['overall_condition'],
      alertnessLevel: json['alertness_level'],
      distressLevel: json['distress_level'],
    );
  }
}

/// Observations data
class ObservationsData {
  final List<String> items;
  final String? additionalNotes;

  ObservationsData({
    this.items = const [],
    this.additionalNotes,
  });

  Map<String, dynamic> toJson() => {
        'items': items,
        if (additionalNotes != null && additionalNotes!.isNotEmpty)
          'additional_notes': additionalNotes,
      };

  factory ObservationsData.fromJson(Map<String, dynamic> json) {
    return ObservationsData(
      items: json['items'] != null ? List<String>.from(json['items']) : [],
      additionalNotes: json['additional_notes'],
    );
  }
}

/// Custom section data
class CustomSectionData {
  final String title;
  final String? icon;
  final String? color;
  final List<CustomSectionOption> options;
  final String? notes;

  CustomSectionData({
    required this.title,
    this.icon,
    this.color,
    this.options = const [],
    this.notes,
  });

  Map<String, dynamic> toJson() => {
        'title': title,
        if (icon != null) 'icon': icon,
        if (color != null) 'color': color,
        'options': options.map((o) => o.toJson()).toList(),
        if (notes != null && notes!.isNotEmpty) 'notes': notes,
      };

  factory CustomSectionData.fromJson(Map<String, dynamic> json) {
    return CustomSectionData(
      title: json['title'] ?? '',
      icon: json['icon'],
      color: json['color'],
      options: json['options'] != null
          ? (json['options'] as List)
              .map((o) => CustomSectionOption.fromJson(o))
              .toList()
          : [],
      notes: json['notes'],
    );
  }
}

/// Custom section option
class CustomSectionOption {
  final String value;
  final bool selected;

  CustomSectionOption({
    required this.value,
    this.selected = false,
  });

  Map<String, dynamic> toJson() => {
        'value': value,
        'selected': selected,
      };

  factory CustomSectionOption.fromJson(Map<String, dynamic> json) {
    return CustomSectionOption(
      value: json['value'] ?? '',
      selected: json['selected'] ?? false,
    );
  }
}

/// Addendum for corrections after signing
class Addendum {
  final String? id;
  final String addendumText;
  final String reasonForAddendum;
  final String? createdById;
  final String? createdByName;
  final String? createdByRole;
  final DateTime? createdAt;
  final DateTime? signedAt;

  Addendum({
    this.id,
    required this.addendumText,
    required this.reasonForAddendum,
    this.createdById,
    this.createdByName,
    this.createdByRole,
    this.createdAt,
    this.signedAt,
  });

  Map<String, dynamic> toJson() => {
        'addendum_text': addendumText,
        'reason_for_addendum': reasonForAddendum,
      };

  factory Addendum.fromJson(Map<String, dynamic> json) {
    return Addendum(
      id: json['id'] ?? json['_id'],
      addendumText: json['addendum_text'] ?? '',
      reasonForAddendum: json['reason_for_addendum'] ?? '',
      createdById: json['created_by_id'] ?? json['created_by']?['id'],
      createdByName: json['created_by_name'] ?? json['created_by']?['name'],
      createdByRole: json['created_by_role'] ?? json['created_by']?['role'],
      createdAt: json['created_at'] != null
          ? DateTime.parse(json['created_at'])
          : null,
      signedAt: json['signed_at'] != null
          ? DateTime.parse(json['signed_at'])
          : null,
    );
  }
}

/// Audit trail entry
class AuditEntry {
  final String? id;
  final String action;
  final Map<String, dynamic>? actionDetails;
  final Map<String, dynamic>? previousValues;
  final Map<String, dynamic>? newValues;
  final String? performedById;
  final String? performedByName;
  final String? performedByRole;
  final String? ipAddress;
  final DateTime? createdAt;

  AuditEntry({
    this.id,
    required this.action,
    this.actionDetails,
    this.previousValues,
    this.newValues,
    this.performedById,
    this.performedByName,
    this.performedByRole,
    this.ipAddress,
    this.createdAt,
  });

  factory AuditEntry.fromJson(Map<String, dynamic> json) {
    return AuditEntry(
      id: json['id'] ?? json['_id'],
      action: json['action'] ?? '',
      actionDetails: json['action_details'],
      previousValues: json['previous_values'],
      newValues: json['new_values'],
      performedById: json['performed_by_id'] ?? json['performed_by']?['id'],
      performedByName: json['performed_by_name'] ?? json['performed_by']?['name'],
      performedByRole: json['performed_by_role'] ?? json['performed_by']?['role'],
      ipAddress: json['ip_address'],
      createdAt: json['created_at'] != null
          ? DateTime.parse(json['created_at'])
          : null,
    );
  }
}

